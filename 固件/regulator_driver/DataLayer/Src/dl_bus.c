/************************************函数实现**************************************************/
/********************************************************************************************
* 函数名称 :   dl_bus_get_bus_mv
* 功能描述 :   母线电压（mV）
*
*               链路：BUS → R_BUS_HI 150k / R_BUS_LO 10k → PB0（ADC1_IN15）→ ×16
*
*               为什么用整数乘而不是浮点：×16 就是左移 4 位，没有舍入误差，
*               也不引入浮点库依赖。16 这个数来源于 (150+10)/10，改电阻时改 DL_BUS_RATIO
*               与本函数的实现必须一起看 —— 如果新比值不是整数，就得换回浮点写法，
*               否则整数除法会悄悄截断。
*
*               ⚠️ 满量程 16 × 3300 = 52800 mV。超过这个数只会读到 52800，
*                  也就是说"读满"既可能是 52.8 V，也可能是 70 V。要区分必须改分压比。
*
* 输入参数 :   无
* 输出参数 :   无
* 返回值   :   母线电压（mV）
*********************************************************************************************/
U32 dl_bus_get_bus_mv
(
    VOID
)
{
    U16 raw;
    U32 pin_mv;

    raw    = bsp_adc_get_raw(1U, BSP_ADC1_IDX_BUS);
    pin_mv = bsp_adc_raw_to_mv(raw);

    /* ×16 = 分压比的倒数。整数左移没有精度损失（DL_BUS_RATIO 就是 16.0F）。 */
    return pin_mv << 4;
}

/********************************************************************************************
* 函数名称 :   dl_bus_get_sc_mv
* 功能描述 :   超容总压（mV）
*
*               2026-10-30 改版后**没有独立的总压通道**：SC+ 就是第 8 节抽头 T8，
*               经 U_CELL_MUX2 选通到 SC_ADC_B。所以这里直接取 dl_cell 的 T8 缓存。
*
*               ⚠️ 14.6 倍分压是“选通后”的比值（68k 对 10k∥10k），换算在 dl_cell.c 统一做，
*                  本函数不再自己乘系数 —— 否则两处系数一改一漏，就会出现 1.87 倍的静默偏差。
*               ⚠️ 更根本的问题：这个值相对 GND_SYS，而超容负极不是 GND_SYS。
*                  真正的超容总压应该减掉 SC− 的电位，见 dl_cell.h 顶部的说明。
*
* 输入参数 :   无
* 输出参数 :   无
* 返回值   :   超容总压（mV，相对 GND_SYS，未扣 SC−）
*********************************************************************************************/
U32 dl_bus_get_sc_mv
(
    VOID
)
{
    /* 还没扫过就先扫一轮：调用者可能是控制环，不能让它拿到恒 0 的反馈。
     * 一轮约 2.3 ms，只在第一次调用时发生。 */
    if (dl_cell_is_scanned() != TRUE)
    {
        dl_cell_scan();
    }

    return dl_cell_get_tap_mv(DL_CELL_NUM);
}

