/********************************************************************************************
 * 母线 / 超容总压 —— 两组分压网络
 *
 * ── 母线 BUS ────────────────────────────────────────────────────────────────
 *   BOM：R_BUS_HI = 150 kΩ ±0.1%（RT1206BRD07150KL）
 *        R_BUS_LO = 10 kΩ  ±0.1%（PTFR0805B10K0N9）
 *        C_BUS_ADC = 1 nF 100 V C0G
 *   分压比 = 10 / (150 + 10) = 1/16  →  V_BUS = 16 × V(pin)
 *   满量程 = 16 × 3.3 V = 52.8 V
 *   额定母线 22.5–37.8 V → 引脚 1.41–2.36 V，余量充足。
 *
 *   ⚠️ 52.8 V 只是 ADC 的量程上限，不是电路的安全上限。
 *      原理图准备文档里 BUS 的器件额定普遍到 80 V（母线电容 80 V、SMCJ43A TVS），
 *      也就是说 43 V 以上的母线在硬件上已经接近 TVS 动作点了。
 *      软件上看到 >52.8 V 只能读到"饱和"，要区分"52.8 V"和"70 V"必须改分压比。
 *
 * ── 超容总压 SC_SUM ─────────────────────────────────────────────────────────
 *   BOM：R_T8_HI = 68 kΩ ±0.1%
 *        R_T8_LO = 10 kΩ ±0.1%
 *        C_T8_FILTER = 1 nF 100 V C0G
 *   分压比 = 10 / (68 + 10) = 1/7.8  →  V_SC = 7.8 × V(pin)
 *   满量程 = 7.8 × 3.3 V = 25.74 V
 *   8S 超容满充 8 × 2.7 = 21.6 V → 引脚 2.77 V，余量只有 0.53 V。
 *   ⚠️ 所以 BW6101 的 2.45 V 档（8 × 2.45 = 19.6 V）才是正常工作的上限，
 *      21.6 V 只是器件绝对最大值。软件门限要按 2.45 V/节那档算，不要按 2.7 V。
 *
 *   ⚠️ 这个通道在芯片里和 AD_T8 是**同一个 ADC 读数**（PB14 / ADC1_IN5），
 *      不是两条独立路径。所以"8 节之和 ≈ 总压"只是一条望远镜恒等式，
 *      不构成交叉校验，也证明不了这条通道本身没坏。
 *      独立的总压比较由 TLV6700 提供，但它有它自己的门限，不是软件能读的。
 ********************************************************************************************/

